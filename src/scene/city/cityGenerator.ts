/**
 * The city after the reference drawing, generated by casting a ray through
 * every pixel into a street of boxes (see `sim/cityGeometry.ts`). Art is
 * authored in full daylight colours; the lighting system tints each depth
 * band for the time of day and weather.
 */

export const HORIZON_Y = CITY_HORIZON;

export type CityLayerName = 'far' | 'mid' | 'near';

export interface WindowRecord {
  x: number;
  y: number;
  w: number;
  h: number;
  /** Exact pixels (world index y·W + x) when the window isn't a plain rectangle. */
  mask?: number[];
}

export type { Ledge };

export interface CityLayer {
  name: CityLayerName;
  art: PixelBuffer;
  windows: WindowRecord[];
}

export interface StreetLampSpot {
  /** Lamp head, in world px. */
  x: number;
  y: number;
  /** Where its pool of light falls on the street. */
  groundY: number;
  scale: number;
  /** On the ground plane, under the lamp head. */
  gx: number;
  depth: number;
}

/** A pool of light thrown on the street (and the shopfronts beside it) by one source. */
export interface LightPool {
  /** Where its art sits in the world. */
  x: number;
  y: number;
  /** Additive light: black is no light, brighter is more. */
  art: PixelBuffer;
  /** What casts it, so it can follow the source: a night stall or a street lamp, by index. */
  source: 'stall' | 'lamp';
  index: number;
}

/** A sign's neon tubes and halo, lit after dark (each sign flickers on its own). */
export interface NeonSign {
  x: number;
  y: number;
  art: PixelBuffer;
  /** A worn-out tube that stutters on and off. */
  broken: boolean;
}

export interface StallSpot {
  gx: number;
  depth: number;
  shift: 'day' | 'night';
}

/** How bright a light pool is at a ground point, for a source at (gx, depth) and a reach in ground px. */
export function poolFalloff(gx: number, depth: number, sgx: number, sdepth: number, reach: number): number {
  const d = Math.hypot(gx - sgx, (depth - sdepth) * FOCAL) / reach;
  return d >= 1 ? 0 : (1 - d * d) ** 1.6;
}

/** Light pool reach (ground px) for each kind of source. */
export const POOL_REACH = { stall: 70, lamp: 58 } as const;

export interface CityLayout {
  layers: CityLayer[];
  /** Things hanging over the street (the skybridge, signs, awnings): drawn over the people beyond them. */
  over: PixelBuffer;
  /** Neon on each sign and billboard (lit after dark), with a soft halo. */
  signs: NeonSign[];
  /** Pools of warm light from the night stalls and street lamps. */
  pools: LightPool[];
  /** Which pixels are the street's paving (graded darker at night, so the pools of light read). */
  streetMask: Uint8Array;
  /** Windows on things hanging over the street (the skybridge). */
  overWindows: WindowRecord[];
  ledges: Ledge[];
  lamps: StreetLampSpot[];
  /** Doorways on the street, on the ground plane (gx at the building line). */
  doors: Array<{ gx: number; depth: number }>;
  /** Where market stalls set up, along both sides of the street, day and night ones alternating. */
  stallSpots: StallSpot[];
}

type Material = 'brick' | 'beige' | 'glass' | 'concrete' | 'stone' | 'roof' | 'metal' | 'sign' | 'awning' | 'bridge' | 'pipe';

interface Building {
  box: Box;
  prepared: PreparedBox;
  id: number;
  material: Material;
  body: number;
  /** Floor height and window pitch (ground px). */
  floor: number;
  pitch: number;
  /** Shops along the street at the foot of its street-side wall. */
  shops: 'left' | 'right' | null;
  seed: number;
  /** The nearest any part of it comes (a ray can't meet it any sooner). */
  near: number;
  neon?: number;
  stripes?: [number, number];
}

const HAZE = 0xb6c6d6;
const BIRD_SCALE = 0.34;
const birdZ = (depth: number) => depthForScale(BIRD_SCALE / depth);
const bandOf = (depth: number): CityLayerName => (depth < 4.2 ? 'near' : depth < 13 ? 'mid' : 'far');

const BODIES: Record<Material, number[]> = {
  brick: [0xa0644a, 0x96583e, 0x8a5240, 0xa86e52],
  beige: [0xd8c8aa, 0xcfbfa0, 0xe0d2b6, 0xc8b898],
  glass: [0x5a7a98, 0x4e6e90, 0x62849e],
  concrete: [0xa8a49c, 0x9c988e, 0xb4b0a6, 0x8e8c86],
  stone: [0xc8ccd0, 0xbcc2c8, 0xd2d4d4],
  roof: [0x8a8680, 0x7e7a74],
  metal: [0x8c9094, 0x7c8084],
  sign: [0xd8d6cc],
  awning: [0xc84a3a],
  bridge: [0x8e8c88],
  pipe: [0x9a9a96],
};

const NEONS = [0xff4a9a, 0x4ae8ff, 0xffb040, 0x9a6aff, 0x6aff9a];

export function generateCity(seed = 20261015): CityLayout {
  const rng = createRng(seed);
  const buildings: Building[] = [];
  const add = (box: Box, material: Material, extra: Partial<Omit<Building, 'box' | 'prepared' | 'id' | 'material'>> = {}) => {
    const bodies = BODIES[material];
    const b: Building = {
      box,
      prepared: prepareBox(box),
      id: buildings.length,
      material,
      body: extra.body ?? bodies[Math.floor(rng() * bodies.length)],
      floor: extra.floor ?? (material === 'glass' ? 12 : material === 'beige' ? 18 : 16),
      pitch: extra.pitch ?? (material === 'glass' ? 10 : material === 'beige' ? 20 : 14),
      shops: extra.shops ?? null,
      seed: Math.floor(rng() * 1e6),
      near: screenBounds(box).near,
      neon: extra.neon,
      stripes: extra.stripes,
    };
    buildings.push(b);
    return b;
  };
  const S = STREET_HALF;
  const ledges: Ledge[] = [];
  const doors: CityLayout['doors'] = [];
  // The market's pitches, either side of the lane: day and night stalls take turns along each side.
  const stallSpots: StallSpot[] = [];
  [1.35, 1.75, 2.3, 2.75, 3.3, 3.9, 4.6, 5.4].forEach((depth, i) => {
    stallSpots.push({ gx: -S + 22, depth, shift: i % 2 === 0 ? 'day' : 'night' }, { gx: S - 22, depth: depth + 0.18, shift: i % 2 === 0 ? 'night' : 'day' });
  });

  // --- The street canyon: buildings shoulder to shoulder either side ---
  const left: Array<[d0: number, d1: number, h: number, m: Material]> = [
    [0.3, 2.4, 150, 'beige'],
    [2.4, 3.3, 280, 'brick'],
    [3.3, 4.6, 230, 'beige'],
    [4.6, 6.2, 330, 'concrete'],
    [6.2, 8.5, 260, 'brick'],
    [8.5, 12, 300, 'glass'],
    [12, 17, 250, 'beige'],
    [17, 25, 380, 'concrete'],
    [25, 45, 320, 'brick'],
  ];
  const right: Array<[d0: number, d1: number, h: number, m: Material]> = [
    [0.3, 3.0, 110, 'concrete'],
    [3.0, 4.2, 190, 'glass'],
    [4.2, 5.6, 160, 'brick'],
    [5.6, 8, 280, 'beige'],
    [8, 11, 220, 'brick'],
    [11, 16, 320, 'concrete'],
    [16, 24, 260, 'beige'],
    [24, 45, 350, 'glass'],
  ];
  for (const [d0, d1, h, m] of left) {
    add(boxFrom(-300 - d0 * 20, -S, d0, d1, 0, h), m, { shops: 'right' });
    if (d1 < 9) doors.push({ gx: -S, depth: d0 + (d1 - d0) * 0.6 });
  }
  for (const [d0, d1, h, m] of right) {
    add(boxFrom(S, 300 + d0 * 20, d0, d1, 0, h), m, { shops: 'left' });
    if (d1 < 9 && d0 > 1) doors.push({ gx: S, depth: d0 + (d1 - d0) * 0.4 });
  }

  // --- Towers at the left, rising out of the top of the view ---
  add(boxFrom(-1000, -640, 2.0, 2.6, 0, 820), 'beige', { pitch: 40, floor: 24 });
  add(boxFrom(-640, -470, 2.2, 2.9, 0, 760), 'glass');
  add(boxFrom(-470, -310, 2.5, 3.4, 0, 580), 'brick');

  // --- Blocks behind the canyon walls, and the skyline beyond ---
  const blockRng = createRng(seed + 1);
  for (let i = 0; i < 46; i++) {
    const depth = randomRange(blockRng, 3, 13);
    const side = i % 2 ? 1 : -1;
    const gx0 = side * randomRange(blockRng, 320, 320 + depth * 380);
    const w = randomRange(blockRng, 120, 320);
    const h = randomRange(blockRng, 150, 520) * (side > 0 && depth < 5 ? 0.6 : 1);
    const m: Material = (['brick', 'beige', 'concrete', 'glass'] as const)[Math.floor(blockRng() * 4)];
    add(boxFrom(gx0, gx0 + side * w, depth, depth + randomRange(blockRng, 0.6, 2), 0, h), m);
  }
  for (let i = 0; i < 80; i++) {
    const depth = randomRange(blockRng, 14, 70);
    const x = randomRange(blockRng, -30, WORLD_WIDTH + 30);
    // Taller towers cluster in the middle of the skyline, as downtown does.
    const central = 1 - Math.min(1, Math.abs(x - 520) / 420);
    const top = randomRange(blockRng, 150, 60) - central * 50;
    const h = CITY_EYE + (CITY_HORIZON - top) * depth;
    const gx = (x - CITY_VANISH_X) * depth;
    const w = randomRange(blockRng, 8, 26) * depth;
    const deep = randomRange(blockRng, 0.5, 3);
    const m: Material = blockRng() < 0.35 ? 'glass' : blockRng() < 0.6 ? 'stone' : 'concrete';
    add(boxFrom(gx - w / 2, gx + w / 2, depth, depth + deep, 0, h), m);
    // Setback crowns and masts on the taller ones.
    const crown = blockRng();
    if (crown < 0.45) add(boxFrom(gx - w * 0.32, gx + w * 0.32, depth + deep * 0.15, depth + deep * 0.85, h, h + randomRange(blockRng, 4, 14) * depth), m);
    if (crown < 0.25) add(boxFrom(gx - 0.8 * depth, gx + 0.8 * depth, depth + deep * 0.5, depth + deep * 0.5 + 0.05, h, h + randomRange(blockRng, 10, 26) * depth), 'metal');
  }
  // The great spire tower, stepping back in tiers to a needle.
  {
    const depth = 22;
    const gx = (552 - CITY_VANISH_X) * depth;
    const tier = (half: number, h0: number, h1: number) => add(boxFrom(gx - half, gx + half, depth, depth + 1.2, h0, h1), 'stone', { pitch: 30, floor: 40, body: 0xd4d2c8 });
    const base = CITY_EYE + (CITY_HORIZON - 64) * depth;
    tier(300, 0, base);
    tier(220, base, base + 420);
    tier(150, base + 420, base + 760);
    tier(90, base + 760, base + 980);
    tier(40, base + 980, base + 1160);
    tier(10, base + 1160, base + 1900);
    // A slimmer modern tower beside it, with a pointed crown.
    const gx2 = (612 - CITY_VANISH_X) * 28;
    const base2 = CITY_EYE + (CITY_HORIZON - 92) * 28;
    add(boxFrom(gx2 - 160, gx2 + 160, 28, 29, 0, base2), 'glass');
    for (let k = 0; k < 5; k++) add(boxFrom(gx2 - 140 + k * 28, gx2 + 140 - k * 28, 28.1, 28.9, base2 + k * 140, base2 + (k + 1) * 140), 'glass');
  }

  // --- A skybridge across the canyon, with pipes under it ---
  add(boxFrom(-S, S, 2.1, 2.3, 100, 120), 'bridge');
  add(boxFrom(-S, S, 2.12, 2.16, 92, 96), 'pipe');
  add(boxFrom(-S, S, 2.2, 2.24, 94, 98), 'pipe');
  ledges.push(edgeLedge(-S + 6, S - 6, 2.1, 120, 'near', 'roof'));

  // --- Rooftops below us on the right: plant, pipes and billboards ---
  add(boxFrom(140, 210, 1.7, 2.1, 110, 130), 'metal');
  // A stair house with its door, a water tank on legs, and a skylight.
  add(boxFrom(250, 292, 1.62, 1.86, 110, 140), 'concrete', { pitch: 1e9, floor: 1e9, body: 0x8e8a82 });
  add(boxFrom(300, 340, 2.0, 2.15, 140, 170), 'metal', { body: 0x7a6a5a });
  for (const [gx, d] of [
    [302, 2.01],
    [336, 2.01],
    [302, 2.13],
    [336, 2.13],
  ] as const) add(boxFrom(gx, gx + 3, d, d + 0.01, 110, 140), 'pipe');
  add(boxFrom(120, 160, 2.35, 2.5, 110, 114), 'glass');
  ledges.push(edgeLedge(250, 292, 1.62, 140, 'near', 'roof'), edgeLedge(300, 340, 2.0, 170, 'near', 'tower'));
  add(boxFrom(230, 280, 2.3, 2.55, 110, 124), 'metal');
  add(boxFrom(96, 104, 1.2, 2.9, 110, 118), 'pipe');
  add(boxFrom(108, 116, 1.2, 2.9, 110, 116), 'pipe');
  add(boxFrom(96, 290, 2.85, 2.9, 110, 118), 'pipe');
  add(boxFrom(150, 270, 2.62, 2.65, 132, 180), 'sign', { neon: NEONS[1] });
  add(boxFrom(150, 156, 2.66, 2.7, 110, 132), 'pipe');
  add(boxFrom(264, 270, 2.66, 2.7, 110, 132), 'pipe');
  add(boxFrom(96, 200, 3.05, 3.08, 200, 248), 'sign', { neon: NEONS[0] });
  add(boxFrom(-230, -110, 2.5, 2.53, 290, 330), 'sign', { neon: NEONS[2] });
  ledges.push(edgeLedge(150, 270, 2.62, 180, 'near', 'billboard'), edgeLedge(96, 200, 3.05, 248, 'near', 'billboard'));
  ledges.push(edgeLedge(140, 210, 1.7, 130, 'near', 'roof'), edgeLedge(100, 300, 1.5, 110, 'near', 'roof'));

  // --- Blade signs and shop awnings along the street ---
  for (const [gx, depth, h0, h1, neon] of [
    [-S, 1.05, 40, 120, NEONS[0]],
    [-S, 1.9, 34, 100, NEONS[3]],
    [-S, 2.9, 60, 150, NEONS[1]],
    [-S, 4.0, 50, 120, NEONS[4]],
    [S, 3.3, 40, 130, NEONS[2]],
    [S, 4.5, 50, 110, NEONS[0]],
    [S, 6.0, 60, 140, NEONS[3]],
  ] as const) {
    const out = gx < 0 ? 1 : -1;
    add(boxFrom(gx, gx + out * 16, depth, depth + 0.015, h0, h1), 'sign', { neon });
  }

  // --- Our own roof: a parapet curving across the lower right, and its floor ---
  {
    // Its edge reaches the bottom of the view right of the street, so the street stays in sight.
    const a = { gx: 11, z: 0.13 * FOCAL };
    const b = { gx: 740, z: 2.3 * FOCAL };
    const angle = Math.atan2(b.z - a.z, b.gx - a.gx);
    const len = Math.hypot(b.z - a.z, b.gx - a.gx);
    const cx = (a.gx + b.gx) / 2;
    const cz = (a.z + b.z) / 2;
    // The coping along the roof's edge...
    // (It runs on past the bottom of the view, right by our feet.)
    add({ gx: cx, depth: cz / FOCAL, halfU: len / 2 + 60, halfW: 16, h0: 164, h1: 174, angle }, 'concrete', { body: 0xd0c8b8, pitch: 1e9, floor: 1e9 });
    // ...on top of the building itself, its side dropping away to the street with rows of windows.
    const out = { gx: Math.sin(angle), z: -Math.cos(angle) };
    add({ gx: cx + out.gx * 400, depth: (cz + out.z * 400) / FOCAL, halfU: len / 2 + 300, halfW: 400, h0: 0, h1: 166, angle }, 'concrete', { body: 0xb8b0a2, pitch: 26, floor: 22 });
    // Pigeons strut along the coping.
    for (let t = 0.1; t < 0.9; t += 0.07) {
      const gx = a.gx + (b.gx - a.gx) * t;
      const depth = (a.z + (b.z - a.z) * t) / FOCAL;
      const p = projectPoint(gx, depth, 174);
      ledges.push({ x0: Math.round(p.x - 3), x1: Math.round(p.x + 3), y: Math.round(p.y), layer: 'near', kind: 'sidewalk', z: birdZ(depth) });
    }
  }

  // --- Cast a ray through every pixel ---
  const bands: Record<CityLayerName, PixelBuffer> = {
    far: new PixelBuffer(WORLD_WIDTH, WORLD_HEIGHT),
    mid: new PixelBuffer(WORLD_WIDTH, WORLD_HEIGHT),
    near: new PixelBuffer(WORLD_WIDTH, WORLD_HEIGHT),
  };
  const neon = new PixelBuffer(WORLD_WIDTH, WORLD_HEIGHT);
  /** Which sign each neon pixel belongs to. */
  const neonOwner = new Int32Array(WORLD_WIDTH * WORLD_HEIGHT).fill(-1);
  const over = new PixelBuffer(WORLD_WIDTH, WORLD_HEIGHT);
  const streetMask = new Uint8Array(WORLD_WIDTH * WORLD_HEIGHT);
  // Boxes that hang over the street, so people further off pass behind them.
  const overhangs = new Set(buildings.filter((b) => b.material === 'bridge' || (b.material === 'sign' && Math.abs(b.box.gx) < STREET_HALF + 20) || (b.material === 'pipe' && Math.abs(b.box.gx) < 1)).map((b) => b.id));
  const owner = new Int32Array(WORLD_WIDTH * WORLD_HEIGHT).fill(-1);
  const zbuf = new Float32Array(WORLD_WIDTH * WORLD_HEIGHT).fill(Number.POSITIVE_INFINITY);
  /** Which face each pixel shows (for inking the edges between faces). */
  const faces = new Uint8Array(WORLD_WIDTH * WORLD_HEIGHT);
  const FACE_CODE: Record<string, number> = { front: 1, back: 2, left: 3, right: 4, top: 5, bottom: 6 };
  const windowPixels = new Map<string, { band: CityLayerName | 'over'; pixels: number[] }>();

  // Bucket boxes by the screen cells they can cover, so each ray only tries a few.
  const CELL = 24;
  const cols = Math.ceil(WORLD_WIDTH / CELL);
  const rows = Math.ceil(WORLD_HEIGHT / CELL);
  const cells: Building[][] = Array.from({ length: cols * rows }, () => []);
  // Nearest first, so once something is hit, everything that can only be further away is skipped.
  for (const b of [...buildings].sort((p, q) => p.near - q.near)) {
    const r = screenBounds(b.box);
    for (let cy = Math.max(0, Math.floor(r.y0 / CELL)); cy <= Math.min(rows - 1, Math.floor(r.y1 / CELL)); cy++) {
      for (let cx = Math.max(0, Math.floor(r.x0 / CELL)); cx <= Math.min(cols - 1, Math.floor(r.x1 / CELL)); cx++) cells[cy * cols + cx].push(b);
    }
  }

  for (let y = 0; y < WORLD_HEIGHT; y++) {
    const bRay = y + 0.5 - CITY_HORIZON;
    for (let x = 0; x < WORLD_WIDTH; x++) {
      const aRay = x + 0.5 - CITY_VANISH_X;
      let bestDepth = Number.POSITIVE_INFINITY;
      let hitBy: Building | null = null;
      for (const b of cells[Math.floor(y / CELL) * cols + Math.floor(x / CELL)]) {
        if (b.near >= bestDepth) break;
        const d = castDepth(b.prepared, aRay, bRay);
        if (d >= 0 && d < bestDepth) {
          bestDepth = d;
          hitBy = b;
        }
      }
      const best: Hit | null = hitBy ? castBox(hitBy.prepared, aRay, bRay) : null;
      const i = y * WORLD_WIDTH + x;
      if (best && hitBy) {
        const overhang = overhangs.has(hitBy.id);
        const band = bandOf(best.depth);
        const { color, window, glow } = shadeBuilding(hitBy, best, x, y);
        (overhang ? over : bands[band]).set(x, y, haze(color, best.depth));
        owner[i] = hitBy.id;
        zbuf[i] = best.depth;
        faces[i] = FACE_CODE[best.face];
        if (window) {
          // Windows on overhangs light up above them, not hidden underneath.
          const key = overhang ? `over:${window}` : window;
          let w = windowPixels.get(key);
          if (!w) windowPixels.set(key, (w = { band: overhang ? 'over' : band, pixels: [] }));
          w.pixels.push(i);
        }
        if (glow !== null) {
          neon.set(x, y, glow);
          neonOwner[i] = hitBy.id;
        }
      } else if (bRay > 0) {
        // The street (or an alley's floor) far below. It all sits in the near band, so it grades as one piece.
        const depth = CITY_EYE / bRay;
        const color = shadeStreet(aRay * depth, depth, x, y);
        bands.near.set(x, y, haze(color, depth));
        zbuf[i] = depth;
        if (Math.abs(aRay * depth) <= STREET_HALF) streetMask[i] = 1;
      }
    }
  }

  // --- Each sign's neon, with a soft two-ring halo, cut out on its own so it can flicker on its own ---
  const signs: NeonSign[] = [];
  {
    const R = 3;
    const halo: Array<[number, number, number, number]> = [];
    for (let y = R; y < WORLD_HEIGHT - R; y++) {
      for (let x = R; x < WORLD_WIDTH - R; x++) {
        if (neon.get(x, y) >= 0) continue;
        let best = -1;
        let who = -1;
        let dist = R * R + 1;
        for (let dy = -R; dy <= R; dy++) {
          for (let dx = -R; dx <= R; dx++) {
            const k = (y + dy) * WORLD_WIDTH + x + dx;
            const d = dx * dx + dy * dy;
            if (neonOwner[k] >= 0 && d < dist) {
              dist = d;
              best = neon.get(x + dx, y + dy);
              who = neonOwner[k];
            }
          }
        }
        if (best < 0) continue;
        // Bright close in, then a dithered outer ring fading out.
        const level = dist <= 2 ? 0.42 : dist <= 5 ? 0.24 : 0.12;
        if (dist <= 2 || bayer(x, y) < (dist <= 5 ? 0.75 : 0.45)) halo.push([x, y, scaleColor(best, level), who]);
      }
    }
    for (const [x, y, c, who] of halo) {
      neon.set(x, y, c);
      neonOwner[y * WORLD_WIDTH + x] = who;
    }
    const bounds = new Map<number, { x0: number; y0: number; x1: number; y1: number }>();
    for (let i = 0; i < neonOwner.length; i++) {
      const o = neonOwner[i];
      if (o < 0) continue;
      const x = i % WORLD_WIDTH;
      const y = Math.floor(i / WORLD_WIDTH);
      const r = bounds.get(o);
      if (!r) bounds.set(o, { x0: x, y0: y, x1: x, y1: y });
      else {
        r.x0 = Math.min(r.x0, x);
        r.y0 = Math.min(r.y0, y);
        r.x1 = Math.max(r.x1, x);
        r.y1 = Math.max(r.y1, y);
      }
    }
    let k = 0;
    for (const [o, r] of bounds) {
      const art = new PixelBuffer(r.x1 - r.x0 + 1, r.y1 - r.y0 + 1);
      for (let y = r.y0; y <= r.y1; y++) for (let x = r.x0; x <= r.x1; x++) if (neonOwner[y * WORLD_WIDTH + x] === o) art.set(x - r.x0, y - r.y0, neon.get(x, y));
      // One tired old tube buzzes on and off.
      signs.push({ x: r.x0, y: r.y0, art, broken: k++ === 2 });
    }
  }

  // --- Ink along every edge, like the drawing's line work: between buildings, faces, sky and street ---
  {
    const bandBuffers = [bands.near, bands.mid, bands.far, over];
    const inked: Array<[number, PixelBuffer, number]> = [];
    for (let y = 1; y < WORLD_HEIGHT; y++) {
      for (let x = 1; x < WORLD_WIDTH; x++) {
        const i = y * WORLD_WIDTH + x;
        const o = owner[i];
        if (o < 0) continue;
        const left = i - 1;
        const up = i - WORLD_WIDTH;
        // The nearer of two touching surfaces carries the line.
        const edge =
          (owner[left] !== o && zbuf[left] >= zbuf[i]) || (owner[up] !== o && zbuf[up] >= zbuf[i]) || (owner[left] === o && faces[left] !== faces[i]) || (owner[up] === o && faces[up] !== faces[i]);
        if (!edge) continue;
        const depth = zbuf[i];
        const target = overhangs.has(o) ? over : bands[bandOf(depth)];
        const c = target.get(x, y);
        if (c < 0) continue;
        // Bold up close, fading to a fine grey line in the distance.
        inked.push([i, target, lerpColor(c, 0x2a2622, Math.max(0.25, 0.7 - depth / 60))]);
      }
    }
    for (const [i, target, c] of inked) target.set(i % WORLD_WIDTH, Math.floor(i / WORLD_WIDTH), c);
    void bandBuffers;
  }

  // --- The railing round the roof terrace at left (thin: drawn, not cast) ---
  const near = bands.near;
  const line = (p: { x: number; y: number }, q: { x: number; y: number }, depth: number, width: number, color: number, light: number) => {
    const steps = Math.ceil(Math.hypot(q.x - p.x, q.y - p.y) * 1.5) + 1;
    for (let s = 0; s <= steps; s++) {
      const t = s / steps;
      const x = p.x + (q.x - p.x) * t;
      const y = p.y + (q.y - p.y) * t;
      for (let k = 0; k < width; k++) {
        const px = Math.round(x);
        const py = Math.round(y + k - width / 2);
        if (px < 0 || py < 0 || px >= WORLD_WIDTH || py >= WORLD_HEIGHT || zbuf[py * WORLD_WIDTH + px] < depth - 0.05) continue;
        near.set(px, py, k === 0 ? light : color);
      }
    }
  };
  const RAIL_GX = -S - 8;
  const roofTop = 150;
  const railDepths: number[] = [];
  for (let d = 0.34; d < 2.38; d += 60 / FOCAL) railDepths.push(d);
  const rail = 0x6a6e72;
  const railLight = 0xb4b8bc;
  for (const d of railDepths) {
    const foot = projectPoint(RAIL_GX, d, roofTop);
    const top = projectPoint(RAIL_GX, d, roofTop + 28);
    const w = Math.max(1, Math.round(3 / d));
    for (let k = 0; k < w; k++) line({ x: foot.x + k, y: foot.y }, { x: top.x + k, y: top.y }, d, 1, k === 0 ? railLight : rail, railLight);
  }
  for (const h of [roofTop + 15, roofTop + 28]) {
    for (let k = 0; k < railDepths.length - 1; k++) {
      const d0 = railDepths[k];
      const d1 = railDepths[k + 1];
      line(projectPoint(RAIL_GX, d0, h), projectPoint(RAIL_GX, d1, h), d0, Math.max(1, Math.round(2.5 / d0)), rail, railLight);
    }
  }
  // Along the terrace's near edge too.
  for (const h of [roofTop + 15, roofTop + 28]) line(projectPoint(RAIL_GX, 0.42, h), projectPoint(-480, 0.42, h), 0.42, 5, rail, railLight);
  for (let gx = RAIL_GX; gx > -480; gx -= 70) line(projectPoint(gx, 0.42, roofTop), projectPoint(gx, 0.42, roofTop + 28), 0.42, 6, rail, railLight);
  // Birds perch along the top rail, and pigeons walk the terrace.
  for (let k = 1; k < railDepths.length - 1; k += 2) {
    const p = projectPoint(RAIL_GX, railDepths[k], roofTop + 28);
    ledges.push({ x0: Math.round(p.x - 2), x1: Math.round(p.x + 2), y: Math.round(p.y) - 1, layer: 'near', kind: 'rail', z: birdZ(railDepths[k]) });
  }
  {
    const p0 = projectPoint(-420, 1.1, roofTop);
    const p1 = projectPoint(-140, 1.1, roofTop);
    ledges.push({ x0: Math.max(4, Math.round(p0.x)), x1: Math.round(p1.x), y: Math.round(p0.y), layer: 'near', kind: 'sidewalk', z: birdZ(1.1) });
  }

  // --- Roof lines to perch on, wherever they show against the sky ---
  for (const b of buildings) {
    const box = b.box;
    if (box.angle || b.material === 'pipe' || b.material === 'awning') continue;
    const d0 = box.depth - box.halfW / FOCAL;
    if (d0 > 30) continue;
    const l = edgeLedge(box.gx - box.halfU + 3, box.gx + box.halfU - 3, d0, box.h1, bandOf(d0), b.material === 'sign' ? 'billboard' : 'roof');
    // Keep only the stretches where it's this building's edge, with open sky (or something far behind) above.
    let start = -1;
    for (let x = l.x0; x <= l.x1 + 1; x++) {
      const ok =
        x <= l.x1 &&
        x >= 0 &&
        x < WORLD_WIDTH &&
        l.y > 4 &&
        l.y < WORLD_HEIGHT &&
        owner[(l.y + 1) * WORLD_WIDTH + x] === b.id &&
        zbuf[(l.y - 4) * WORLD_WIDTH + x] > d0 + 0.5;
      if (ok && start < 0) start = x;
      if (!ok && start >= 0) {
        if (x - start >= 3) ledges.push({ ...l, x0: start, x1: x - 1 });
        start = -1;
      }
    }
  }

  // --- Shop awnings: sloped canvas over the shopfronts (kept clear of the stalls and lamps) ---
  const lampDepths = [1.3, 2.05, 2.85, 3.9, 5.1, 6.6, 8.6];
  {
    const awn = new PixelBuffer(WORLD_WIDTH, WORLD_HEIGHT);
    const awnDepth = new Float32Array(WORLD_WIDTH * WORLD_HEIGHT).fill(Number.POSITIVE_INFINITY);
    const awnRng = createRng(seed + 7);
    const STRIPES: Array<[number, number]> = [
      [0xd8503e, 0xf0e4d0],
      [0x3e6ab0, 0xf0e4d0],
      [0x3c8a5a, 0xf0e4d0],
      [0xe0a030, 0x7a3e2a],
      [0x8a4a8a, 0xf0e4d0],
    ];
    const splat = (gx: number, depth: number, h: number, color: number) => {
      const p = projectPoint(gx, depth, h);
      const x = Math.floor(p.x);
      const y = Math.floor(p.y);
      if (x < 0 || y < 0 || x >= WORLD_WIDTH || y >= WORLD_HEIGHT) return;
      const i = y * WORLD_WIDTH + x;
      if (zbuf[i] < depth - 0.02 || awnDepth[i] <= depth) return;
      awnDepth[i] = depth;
      awn.set(x, y, color);
    };
    for (const side of [-1, 1]) {
      for (let d0 = 0.55, len = 0; d0 < 6.2; d0 += len + 0.02 + awnRng() * 0.04) {
        // Each shop's canopy runs 50–90 ground px along its front.
        len = 0.07 + awnRng() * 0.06;
        const d1 = d0 + len;
        const clash = stallSpots.some((sp) => Math.sign(sp.gx) === side && sp.depth > d0 - 0.17 && sp.depth < d1 + 0.12) || lampDepths.some((ld) => ld > d0 - 0.05 && ld < d1 + 0.05);
        if (clash || awnRng() < 0.25) continue;
        const [ca, cb] = STRIPES[Math.floor(awnRng() * STRIPES.length)];
        const wall = side * S;
        const out = side * (S - 17);
        const H_TOP = 36;
        const H_LOW = 25;
        // Seen from this high, an awning is steeply foreshortened along the street: stripe it only where
        // each stripe still gets a couple of pixels, else it's plain canvas with a contrasting valance.
        const spanY = projectPoint(wall, d0, H_TOP).y - projectPoint(wall, d1, H_TOP).y;
        const stripes = Math.floor(spanY / 2.2);
        const scallops = Math.max(1, Math.round(spanY / 2.2));
        const stepsT = Math.ceil(24 / d0) + 2;
        const stepsQ = Math.ceil(((80 + 200) * len) / (d0 * d0) * 2) + 4;
        for (let a = 0; a <= stepsQ; a++) {
          const q = a / stepsQ;
          const depth = d0 + len * q;
          const stripe = stripes >= 2 ? Math.min(stripes - 1, Math.floor(q * stripes)) : 0;
          const base = stripe % 2 === 0 ? ca : cb;
          // The sloping canvas: shaded under the wall, catching the light towards its edge.
          for (let b = 0; b <= stepsT; b++) {
            const t = b / stepsT;
            splat(wall + (out - wall) * t, depth, H_TOP + (H_LOW - H_TOP) * t, scaleColor(base, 0.78 + 0.28 * t));
          }
          // The scalloped valance hanging from its outer edge.
          const frac = q * scallops - Math.floor(q * scallops);
          const drop = 5 - 2.5 * Math.abs(frac - 0.5) * 2;
          const trim = stripes >= 2 ? base : cb;
          for (let v = 0; v <= drop; v += Math.min(0.5, depth * 0.6)) splat(out, depth - 0.0005, H_LOW - v, scaleColor(trim, 0.86));
          // Its shadow on the pavement below.
          for (let b = 0; b <= stepsT; b++) {
            const p = projectPoint(wall + (out - wall - side * 3) * (b / stepsT), depth, 0);
            const x = Math.floor(p.x);
            const y = Math.floor(p.y);
            if (x < 0 || y < 0 || x >= WORLD_WIDTH || y >= WORLD_HEIGHT || !streetMask[y * WORLD_WIDTH + x]) continue;
            const c = near.get(x, y);
            if (c >= 0) near.set(x, y, scaleColor(c, 0.8));
          }
        }
      }
    }
    // Ink round each awning, then hang them over the street.
    const ink: number[] = [];
    for (let y = 1; y < WORLD_HEIGHT - 1; y++) {
      for (let x = 1; x < WORLD_WIDTH - 1; x++) {
        const i = y * WORLD_WIDTH + x;
        if (awn.isSet(x, y)) continue;
        const nd = Math.min(awnDepth[i - 1], awnDepth[i + 1], awnDepth[i - WORLD_WIDTH], awnDepth[i + WORLD_WIDTH]);
        if (Number.isFinite(nd) && zbuf[i] >= nd - 0.02) ink.push(i);
      }
    }
    for (const i of ink) awn.set(i % WORLD_WIDTH, Math.floor(i / WORLD_WIDTH), 0x3a2a24);
    over.draw(awn, 0, 0);
  }

  // --- Windows, as lights to switch on after dark ---
  const windows: Record<CityLayerName, WindowRecord[]> = { far: [], mid: [], near: [] };
  const overWindows: WindowRecord[] = [];
  for (const { band, pixels } of windowPixels.values()) {
    let x0 = WORLD_WIDTH;
    let y0 = WORLD_HEIGHT;
    let x1 = 0;
    let y1 = 0;
    for (const i of pixels) {
      const x = i % WORLD_WIDTH;
      const y = Math.floor(i / WORLD_WIDTH);
      x0 = Math.min(x0, x);
      x1 = Math.max(x1, x);
      y0 = Math.min(y0, y);
      y1 = Math.max(y1, y);
    }
    const w = x1 - x0 + 1;
    const h = y1 - y0 + 1;
    (band === 'over' ? overWindows : windows[band]).push({ x: x0, y: y0, w, h, mask: pixels.length === w * h ? undefined : pixels });
  }

  // --- Street lamps along both kerbs: iron poles and lanterns, hidden by whatever stands in front ---
  const lamps: StreetLampSpot[] = [];
  const paint = (target: PixelBuffer, x: number, y: number, depth: number, color: number) => {
    x = Math.round(x);
    y = Math.round(y);
    if (x < 0 || y < 0 || x >= WORLD_WIDTH || y >= WORLD_HEIGHT || zbuf[y * WORLD_WIDTH + x] < depth - 0.03) return;
    target.set(x, y, color);
  };
  for (const depth of lampDepths) {
    for (const side of [-1, 1]) {
      const gx = side * (S - 8);
      const headGx = gx - side * 7;
      const target = bands[bandOf(depth)];
      const scale = 1 / depth;
      const pole = projectPoint(gx, depth, 0);
      const poleTop = projectPoint(gx, depth, 40);
      const w = Math.max(1, Math.round(2.4 / depth));
      for (let y = Math.round(poleTop.y); y <= Math.round(pole.y); y++) for (let k = 0; k < w; k++) paint(target, pole.x + k, y, depth, k === 0 ? 0x5a5e66 : 0x2e3036);
      // The arm reaching out over the street.
      for (let t = 0; t <= 1; t += 0.05) {
        const p = projectPoint(gx + (headGx - gx) * t, depth, 40 + Math.sin(t * Math.PI) * 2);
        paint(target, p.x, p.y, depth, 0x2e3036);
      }
      // A lantern: a dark hood over a pale glass that glows after dark.
      const head = projectPoint(headGx, depth, 37);
      const hoodW = Math.max(2, Math.round(9 * scale));
      const hoodH = Math.max(1, Math.round(2.5 * scale));
      const glassW = Math.max(1, Math.round(6 * scale));
      const glassH = Math.max(1, Math.round(4 * scale));
      for (let y = 0; y < hoodH; y++) for (let x = 0; x < hoodW - y * 2; x++) paint(target, head.x - hoodW / 2 + y + x, head.y - hoodH + y, depth, 0x26282e);
      for (let y = 0; y < glassH; y++) for (let x = 0; x < glassW; x++) paint(target, head.x - glassW / 2 + x, head.y + y, depth, x === 0 ? 0xc8c0a8 : 0xe0d8c0);
      const ground = projectPoint(headGx, depth, 0);
      lamps.push({ x: Math.round(head.x), y: Math.round(head.y + glassH / 2), groundY: Math.round(ground.y), scale, gx: headGx, depth });
      ledges.push({ x0: Math.round(Math.min(poleTop.x, head.x)), x1: Math.round(Math.max(poleTop.x, head.x)), y: Math.round(poleTop.y) - 1, layer: bandOf(depth), kind: 'lamp', z: birdZ(depth) });
    }
  }

  // --- Pools of light from the night stalls and the lamps, on the paving and the shopfronts beside it ---
  const pools: LightPool[] = [];
  const RAMPS = {
    stall: [0, 0x1c0e04, 0x3c1e08, 0x62300e, 0x8e4816, 0xbc6820, 0xe8922e],
    lamp: [0, 0x1a1408, 0x362a12, 0x58441c, 0x7c6026, 0xa48034, 0xcca044],
  } as const;
  const makePool = (source: 'stall' | 'lamp', index: number, sgx: number, sdepth: number, strength: number) => {
    const reach = POOL_REACH[source];
    let x0 = WORLD_WIDTH;
    let y0 = WORLD_HEIGHT;
    let x1 = 0;
    let y1 = 0;
    for (let k = 0; k < 24; k++) {
      const a = (k / 24) * Math.PI * 2;
      const depth = (sdepth * FOCAL + Math.sin(a) * reach) / FOCAL;
      if (depth < 0.2) continue;
      for (const h of [0, 80]) {
        const p = projectPoint(sgx + Math.cos(a) * reach, depth, h);
        x0 = Math.min(x0, p.x);
        x1 = Math.max(x1, p.x);
        y0 = Math.min(y0, p.y);
        y1 = Math.max(y1, p.y);
      }
    }
    x0 = Math.max(0, Math.floor(x0));
    y0 = Math.max(0, Math.floor(y0));
    x1 = Math.min(WORLD_WIDTH - 1, Math.ceil(x1));
    y1 = Math.min(WORLD_HEIGHT - 1, Math.ceil(y1));
    if (x1 < x0 || y1 < y0) return;
    const art = new PixelBuffer(x1 - x0 + 1, y1 - y0 + 1);
    const ramp = RAMPS[source];
    // Each pool dithers on its own offset, so overlapping pools don't stack into one pattern.
    const ox = index * 3 + (source === 'lamp' ? 1 : 0);
    const oy = index * 2;
    let lit = false;
    for (let y = y0; y <= y1; y++) {
      for (let x = x0; x <= x1; x++) {
        const i = y * WORLD_WIDTH + x;
        const d = zbuf[i];
        const gx = (x + 0.5 - CITY_VANISH_X) * d;
        let f = 0;
        if (owner[i] < 0 && streetMask[i]) f = poolFalloff(gx, d, sgx, sdepth, reach);
        else if (owner[i] >= 0 && !overhangs.has(owner[i])) {
          // The shopfronts beside the street catch it too, fading up the wall.
          const b = buildings[owner[i]];
          const facing = (b.shops === 'right' && faces[i] === 4) || (b.shops === 'left' && faces[i] === 3);
          const h = CITY_EYE - (y + 0.5 - CITY_HORIZON) * d;
          if (facing && h < 80) f = poolFalloff(gx, d, sgx, sdepth, reach * 1.1) * (1 - h / 80) ** 1.2 * 0.85;
        }
        const level = f * strength * (ramp.length - 1);
        if (level <= 0.05) continue;
        let step = Math.floor(level);
        if (level - step > bayer(x + ox, y + oy)) step++;
        step = Math.min(ramp.length - 1, step);
        if (step === 0) continue;
        art.set(x - x0, y - y0, ramp[step]);
        lit = true;
      }
    }
    if (lit) pools.push({ x: x0, y: y0, art, source, index });
  };
  stallSpots.forEach((spot, i) => {
    if (spot.shift === 'night') makePool('stall', i, spot.gx * 0.8, spot.depth, 1);
  });
  lamps.forEach((lamp, i) => makePool('lamp', i, lamp.gx, lamp.depth, 0.85));

  return {
    layers: (['far', 'mid', 'near'] as const).map((name) => ({ name, art: bands[name], windows: windows[name] })),
    over,
    overWindows,
    signs,
    pools,
    streetMask,
    ledges,
    lamps,
    doors,
    stallSpots,
  };
}

/** A building's front-top edge as a perch, on screen. */
function edgeLedge(gx0: number, gx1: number, depth: number, h: number, layer: CityLayerName, kind: string): Ledge {
  const a = projectPoint(gx0, depth, h);
  const b = projectPoint(gx1, depth, h);
  return { x0: Math.round(Math.min(a.x, b.x)), x1: Math.round(Math.max(a.x, b.x)), y: Math.round(a.y) - 1, layer, kind, z: birdZ(depth) };
}

/** Screen rectangle a box can cover (from its eight corners). */
function screenBounds(box: Box): { x0: number; y0: number; x1: number; y1: number; near: number } {
  const cos = Math.cos(box.angle ?? 0);
  const sin = Math.sin(box.angle ?? 0);
  let x0 = Number.POSITIVE_INFINITY;
  let x1 = Number.NEGATIVE_INFINITY;
  let y0 = Number.POSITIVE_INFINITY;
  let y1 = Number.NEGATIVE_INFINITY;
  let near = Number.POSITIVE_INFINITY;
  for (const su of [-1, 1]) {
    for (const sw of [-1, 1]) {
      const gx = box.gx + cos * su * box.halfU - sin * sw * box.halfW;
      const z = box.depth * FOCAL + sin * su * box.halfU + cos * sw * box.halfW;
      const d = z / FOCAL;
      if (d <= 0.05) return { x0: 0, y0: 0, x1: WORLD_WIDTH, y1: WORLD_HEIGHT, near: 0 };
      near = Math.min(near, d);
      for (const h of [box.h0, box.h1]) {
        const p = projectPoint(gx, d, h);
        x0 = Math.min(x0, p.x);
        x1 = Math.max(x1, p.x);
        y0 = Math.min(y0, p.y);
        y1 = Math.max(y1, p.y);
      }
    }
  }
  return { x0: Math.floor(x0) - 1, y0: Math.floor(y0) - 1, x1: Math.ceil(x1) + 1, y1: Math.ceil(y1) + 1, near };
}

/** Atmospheric perspective: distant things fade into the haze. */
function haze(color: number, depth: number): number {
  const amount = Math.min(0.58, Math.max(0, (depth - 2.5) / 44) ** 0.8);
  return amount > 0 ? lerpColor(color, HAZE, amount) : color;
}

const FACE_LIGHT: Record<string, number> = { front: 0.92, back: 0.7, left: 0.78, right: 1.0, top: 1.1, bottom: 0.6 };

/** The colour of a building where a ray met it, plus the window it's part of and any neon there. */
function shadeBuilding(b: Building, hit: Hit, x: number, y: number): { color: number; window: string | null; glow: number | null } {
  const box = b.box;
  const light = FACE_LIGHT[hit.face];
  const screenPx = hit.depth; // ground px per screen px here
  // Coordinates across the face: s along it, t up it.
  const side = hit.face === 'left' || hit.face === 'right';
  const s = side ? hit.w + box.halfW : hit.u + box.halfU;
  const t = hit.h - box.h0;
  const along = side ? box.halfW * 2 : box.halfU * 2;
  let window: string | null = null;
  let glow: number | null = null;
  let color = b.body;

  switch (b.material) {
    case 'roof':
    case 'metal':
    case 'pipe': {
      if (b.material === 'pipe') color = hit.face === 'top' ? 0xb8b8b4 : scaleColor(b.body, 0.85);
      else if (b.material === 'metal' && hit.face !== 'top' && Math.floor(s / 4) % 2 === 0) color = scaleColor(b.body, 0.85);
      return { color: scaleColor(color, light), window, glow };
    }
    case 'awning': {
      const [a, c] = b.stripes ?? [0xc84a3a, 0xf0e0d0];
      color = Math.floor((side ? s : hit.w) / 10) % 2 === 0 ? a : c;
      return { color: scaleColor(color, hit.face === 'top' ? 1.05 : 0.8), window, glow };
    }
    case 'sign': {
      if (hit.face !== 'front' && hit.face !== 'back') return { color: scaleColor(0x5a5c60, light), window, glow };
      // A framed panel with a bold glyph on it, the glyph lit in neon after dark.
      const u = s / along;
      const v = t / (box.h1 - box.h0);
      const frame = Math.min(u, 1 - u) * along < Math.max(2.5, screenPx * 1.2) || Math.min(v, 1 - v) * (box.h1 - box.h0) < Math.max(2.5, screenPx * 1.2);
      if (frame) return { color: 0x4a4c50, window, glow };
      const g = glyph(u, v, b.seed, screenPx / Math.min(along, box.h1 - box.h0));
      if (g) {
        glow = b.neon ?? NEONS[0];
        return { color: 0x3a3c44, window, glow };
      }
      // The panel is backlit after dark, as in the night drawing.
      return { color: lerpColor(0xe2e0d6, 0xc8c6bc, v), window, glow: scaleColor(b.neon ?? NEONS[0], 0.4) };
    }
    case 'bridge': {
      // Concrete deck with a dark band of windows and a truss.
      const band = t > 5 && t < 12;
      const truss = Math.abs(((s / 16) % 1) - t / 16) < 0.08 || Math.abs(((s / 16) % 1) - (1 - t / 16)) < 0.08;
      color = band ? (Math.floor(s / 8) % 2 ? 0x4a5a6a : 0x6a7a8a) : truss ? 0x5a5a58 : b.body;
      if (band && hit.face === 'front') window = `${b.id}:bridge:${Math.floor(s / 16)}`;
      return { color: scaleColor(color, light), window, glow };
    }
  }

  if (hit.face === 'top' && (box.angle || box.depth < 1.6)) {
    // Our parapet's coping and the terrace: smooth concrete slabs.
    const along = box.angle ? hit.u : hit.w;
    color = Math.abs(along % 60) < hit.depth * 1.1 ? scaleColor(b.body, 0.86) : lerpColor(scaleColor(b.body, 1.08), b.body, valueNoise(hit.u, hit.w, 20, b.seed));
    return { color: scaleColor(color, 1.04), window, glow };
  }
  if (hit.face === 'top') {
    // Flat roofs: tar and gravel, a lighter parapet round the edge.
    const edge = Math.min(box.halfU - Math.abs(hit.u), box.halfW - Math.abs(hit.w)) < 5;
    color = edge ? scaleColor(b.body, 1.12) : ditherRamp([0x7a7672, 0x86827c, 0x928e86], valueNoise(hit.u, hit.w, 9, b.seed), x, y);
    return { color, window, glow };
  }

  // Walls: brick coursing, concrete panels, glass curtain walls; and windows.
  const streetSide = (b.shops === 'right' && hit.face === 'right') || (b.shops === 'left' && hit.face === 'left');
  const floorPx = b.floor / screenPx;
  const pitchPx = b.pitch / screenPx;
  if (streetSide && t < 22) {
    // Shopfronts at street level: big windows between piers, a door now and then.
    const bay = Math.floor(s / 40);
    const sf = s - bay * 40;
    const glass = sf > 4 && sf < 34 && t > 3 && t < 18;
    if (glass) {
      window = `${b.id}:shop:${bay}`;
      color = lerpColor(0x4a5868, 0x8aa0b0, (t - 3) / 15);
      if (pixelHash(bay, 1, b.seed) < 0.25 && sf > 14 && sf < 24) color = 0x2a2420;
    } else color = scaleColor(b.body, 0.8);
    return { color: scaleColor(color, light), window, glow };
  }
  if (floorPx < 2.2 || pitchPx < 2.2) {
    // Too far to make out windows: floors as faint bands, lit windows as scattered dots.
    const row = Math.floor(t / b.floor);
    if (floorPx >= 1.4 && t - row * b.floor < b.floor * 0.45) color = scaleColor(b.body, b.material === 'glass' ? 1.12 : 0.88);
    if (pixelHash(x, y, b.seed) < 0.12) window = `${b.id}:${hit.face}:g${Math.floor(pixelHash(x, y, b.seed + 1) * 8)}`;
    if (b.material === 'glass') color = lerpColor(color, 0x9ab8d4, Math.max(0, 0.4 - t / (box.h1 * 2)));
    return { color: scaleColor(color, light), window, glow };
  }
  const row = Math.floor(t / b.floor);
  const tf = t - row * b.floor;
  const col = Math.floor(s / b.pitch);
  const sf = s - col * b.pitch;
  const winW = b.material === 'glass' ? b.pitch - Math.max(1.2, screenPx) : b.material === 'beige' ? b.pitch * 0.62 : b.pitch * 0.5;
  const winH = b.material === 'glass' ? b.floor - Math.max(1.2, screenPx) : b.floor * 0.55;
  const winS0 = (b.pitch - winW) / 2;
  const winT0 = b.material === 'glass' ? 0 : b.floor * 0.25;
  const inWindow = row > 0 && t < box.h1 - box.h0 - 4 && sf >= winS0 && sf < winS0 + winW && tf >= winT0 && tf < winT0 + winH && s > 3 && s < along - 3;
  if (inWindow) {
    window = `${b.id}:${hit.face}:${row}:${col}`;
    // Glass catches the sky: lighter higher up and towards one side, with a glint.
    const sky = 0.35 + (tf - winT0) / winH * -0.25 + (pixelHash(col, row, b.seed) - 0.5) * 0.3;
    color = lerpColor(0x34404e, 0xa8c4dc, Math.max(0, Math.min(1, sky + (b.material === 'glass' ? 0.2 : 0))));
    if (b.material !== 'glass' && tf - winT0 < 1) color = scaleColor(b.body, 0.6);
    return { color: scaleColor(color, light), window, glow };
  }
  if (b.material === 'brick' && screenPx < 1 && Math.floor(t / 3) % 2 === 0 && (s + (Math.floor(t / 3) % 4 === 0 ? 3 : 0)) % 6 < 0.8) color = scaleColor(b.body, 0.85);
  // Weathering streaks under the windows.
  if (bayer(x, y) < 0.08) color = scaleColor(color, 0.94);
  return { color: scaleColor(color, light), window, glow };
}

/** Strokes of a made-up glyph on a sign (u, v in 0..1): bold curves and bars. */
function glyph(u: number, v: number, seed: number, pixel: number): boolean {
  const width = Math.max(0.06, pixel * 1.2);
  const kind = seed % 4;
  const cx = 0.5;
  const cy = 0.5;
  const du = u - cx;
  const dv = (v - cy) * 1.4;
  if (kind === 0) {
    // A ring with a tail.
    const r = Math.hypot(du, dv);
    return Math.abs(r - 0.28) < width || (u > 0.55 && u < 0.55 + width * 1.5 && v < 0.5 && v > 0.15);
  }
  if (kind === 1) {
    // A wave.
    return Math.abs(dv * 0.7 - Math.sin(du * 9) * 0.12) < width && Math.abs(du) < 0.35;
  }
  if (kind === 2) {
    // Stacked bars.
    return Math.abs(du) < 0.3 && [0.25, 0.5, 0.75].some((y) => Math.abs(v - y) < width * 0.8);
  }
  // A zigzag.
  return Math.abs(du) < 0.32 && Math.abs(dv - Math.abs(((du * 4 + 4) % 2) - 1) * 0.3 + 0.15) < width;
}

/** The street far below: warm paving with kerbs and gutters, alleys between buildings. */
function shadeStreet(gx: number, depth: number, x: number, y: number): number {
  const a = Math.abs(gx);
  if (a > STREET_HALF) return lerpColor(0x4a4440, 0x6a625a, valueNoise(x, y, 4, 9));
  const z = depth * FOCAL;
  let level = 0.55 + (valueNoise(gx, z, 30, 3) - 0.5) * 0.4;
  // Shade towards the walls, where the sun doesn't reach.
  level -= Math.max(0, (a - 56) / 24) * 0.3;
  // Paving joints, while they're big enough to see: a row is a joint if a joint line falls inside it
  // (testing the row's whole span along the street, so they don't flicker in and out with distance).
  const zTop = (CITY_EYE / Math.max(0.5, y - CITY_HORIZON)) * FOCAL;
  const zBottom = (CITY_EYE / (y + 1 - CITY_HORIZON)) * FOCAL;
  const crossJoint = zTop - zBottom < 13 && Math.floor(zTop / 26) !== Math.floor(zBottom / 26);
  if (depth < 4 && (crossJoint || ((gx + 400) % 22) < depth)) level -= 0.15;
  // Kerbs and gutters either side of the lane.
  if (Math.abs(a - 62) < depth * 0.8) return 0x8a7a64;
  return ditherRamp([0xa8885e, 0xb89668, 0xc8a676, 0xd8b686, 0xe4c494], level, x, y);
}

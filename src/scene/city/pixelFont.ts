const FACES: Record<FontFace, Record<string, string[]>> = { small: SMALL, bold: BOLD };

/** The face's letter height (px). */
export const FONT_HEIGHT: Record<FontFace, number> = { small: 5, bold: 7 };

export function glyphFor(ch: string, face: FontFace): string[] | undefined {
  return FACES[face][ch] ?? FACES[face][ch.toUpperCase()];
}

/** Width of a line of text (px), with one px between letters. */
export function textWidth(text: string, face: FontFace): number {
  let w = 0;
  for (const ch of text) w += (glyphFor(ch, face)?.[0].length ?? 3) + 1;
  return Math.max(0, w - 1);
}

/**
 * Draw a line of text with its top-left at (x, y). `scale` doubles (or more)
 * every pixel; `color` may be a function of the pixel for gradients. Returns
 * the width drawn.
 */
export function drawText(
  buf: PixelBuffer,
  text: string,
  x: number,
  y: number,
  color: number | ((px: number, py: number) => number),
  face: FontFace = 'small',
  scale = 1,
): number {
  let cx = x;
  for (const ch of text) {
    const g = glyphFor(ch, face) ?? glyphFor('?', face)!;
    drawRows(buf, g, cx, y, color, scale);
    cx += (g[0].length + 1) * scale;
  }
  return cx - x - scale;
}

/** Draw one made-up glyph (5×5, or scaled). */
export function drawGlyph(buf: PixelBuffer, index: number, x: number, y: number, color: number | ((px: number, py: number) => number), scale = 1): void {
  drawRows(buf, GLYPHS[((index % GLYPHS.length) + GLYPHS.length) % GLYPHS.length], x, y, color, scale);
}

function drawRows(buf: PixelBuffer, rows: string[], x: number, y: number, color: number | ((px: number, py: number) => number), scale: number): void {
  for (let r = 0; r < rows.length; r++) {
    for (let c = 0; c < rows[r].length; c++) {
      if (rows[r][c] !== '#') continue;
      for (let sy = 0; sy < scale; sy++) {
        for (let sx = 0; sx < scale; sx++) {
          const px = x + c * scale + sx;
          const py = y + r * scale + sy;
          if (px < 0 || py < 0 || px >= buf.width || py >= buf.height) continue;
          buf.set(px, py, typeof color === 'number' ? color : color(px, py));
        }
      }
    }
  }
}

/** Whether a glyph cell is ink, sampling a glyph stretched over a w×h box (for signs drawn per pixel). */
export function glyphInk(index: number, u: number, v: number): boolean {
  const g = GLYPHS[((index % GLYPHS.length) + GLYPHS.length) % GLYPHS.length];
  const r = Math.min(g.length - 1, Math.max(0, Math.floor(v * g.length)));
  const c = Math.min(g[0].length - 1, Math.max(0, Math.floor(u * g[0].length)));
  return g[r][c] === '#';
}

/** Whether a letter cell is ink, sampling the bold face stretched over a box. */
export function letterInk(ch: string, u: number, v: number, face: FontFace = 'bold'): boolean {
  const g = glyphFor(ch, face);
  if (!g) return false;
  const r = Math.min(g.length - 1, Math.max(0, Math.floor(v * g.length)));
  const c = Math.min(g[0].length - 1, Math.max(0, Math.floor(u * g[0].length)));
  return g[r][c] === '#';
}

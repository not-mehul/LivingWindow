/**
 * The interface's pixel typeface: a proportional bitmap face drawn for
 * reading, with lowercase. Each glyph is up to nine rows on the pixel grid:
 * rows 0–6 sit above the baseline (capitals fill all seven, lowercase the
 * lower five), rows 7–8 hold descenders. `#` is ink.
 *
 * Its capitals follow the city signs' bold 5×7 letters, so the tablet and
 * the billboards share a hand. It is turned into a real web font by
 * `fontBuilder.ts`, so the panel's text stays real, selectable text.
 */

export interface PixelGlyph {
  /** Ink columns (the advance adds one column of space). */
  width: number;
  /** Rows from the top of the cap height downwards; missing rows are blank. */
  rows: readonly string[];
}

/** Rows above the baseline (cap height). */
export const CAP_ROWS = 7;
/** Rows of the em (cap height, descenders and a row of headroom). */
export const EM_ROWS = 10;

const _ = '';
/** A glyph from its rows; the width is the widest row. */
const g = (...rows: string[]): PixelGlyph => ({ width: Math.max(...rows.map((r) => r.length)), rows });
/** A lowercase glyph: two blank rows above the x-height. */
const x = (...rows: string[]): PixelGlyph => g(_, _, ...rows);

